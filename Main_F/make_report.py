def md(df, floatfmt=2):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)


def tbl(cm):
    s = summ[summ.cost_model == cm].copy()
    s = s[["size", "algorithm", "expanded", "generated", "runtime_ms", "peak_mem_kb",
           "travel_time", "transfers", "fare", "optimal_pct", "mean_gap_pct"]]
    s.columns = ["Size", "Algorithm", "Expanded", "Generated", "Time (ms)", "Mem (KiB)",
                 "Route time (min)", "Transfers", "Fare", "Optimal (%)", "Mean gap (%)"]
    return md(s)


def saving(cm):
    d = raw[raw.cost_model == cm]
    out = []
    for size in ("small", "medium", "large"):
        x = d[d["size"] == size]
        dj = x[x.algorithm == "Dijkstra"].set_index("pair"); a = x[x.algorithm == "A* (admissible)"].set_index("pair")
        red = 100 * (1 - a.expanded / dj.expanded)
        for cls in ("short", "medium", "long"):
            m = dj.dist_class == cls
            out.append(dict(Size=size, Distance=cls, **{"Dijkstra expanded": dj.expanded[m].mean(),
                            "A* expanded": a.expanded[m].mean(), "Saving (%)": red[m].mean()}))
    return pd.DataFrame(out)


